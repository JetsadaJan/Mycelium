import { describe, expect, it } from 'vitest';
import {
  buildVaultSnapshot,
  extractNoteSectionOrBlock,
  linkTermInMarkdown,
  markSelectionAsAiSafely,
  normalizeObsidianFormattedLinks,
  parseNote,
  serializeMarkdownLossless,
  stripObsidianComments,
  unmarkAiSpanSafely,
  verifyEntireMarkdown,
  verifySegmentInMarkdown,
} from '../vaultEngine';
import { ObsidianGraphSimulator, filterLocalSubgraph } from '../graphSim';

describe('Mycelium Obsidian-Compatible Engine & AI Verifier', () => {
  const sampleNote = `---
title: Mycelium Network
aliases: [Mycelium, Wood Wide Web]
tags: [biology, network]
ai_status: partial
ai_source: claude-code
---

# Mycelium Network

Mycelium connects [[Fungi|Kingdom Fungi]] and [[Mycorrhiza]].

> [!ai] Generated by AI (claude-code)
> Networks propagate electrical spikes to [[Knowledge Graph]] models.

Signal velocity reaches ==[AI:gemini] 0.5 to 5 mm/s== in soil.`;

  it('parses YAML frontmatter, WikiLinks, aliases, callout AI blocks, and inline AI spans', () => {
    const doc = parseNote('Mycelium Network.md', sampleNote);
    expect(doc.title).toBe('Mycelium Network');
    expect(doc.aliases).toEqual(['Mycelium', 'Wood Wide Web']);
    expect(doc.epistemic_status).toBe('partial');
    expect(doc.outgoing_links).toHaveLength(3);
    expect(doc.outgoing_links[0].display_text).toBe('Kingdom Fungi');
    expect(doc.ai_segments).toHaveLength(2);
    expect(doc.ai_segments[0].kind).toBe('callout');
    expect(doc.ai_segments[1].kind).toBe('inline');
  });

  it('verifies individual AI segments and transitions note status to verified when all are approved', () => {
    const afterBlock = verifySegmentInMarkdown(sampleNote, 'ai-seg-1', '2026-11-05');
    expect(afterBlock).not.toContain('> [!ai]');
    expect(afterBlock).toContain('Networks propagate electrical spikes to [[Knowledge Graph]] models.');
    expect(afterBlock).toContain('ai_status: partial');

    const afterAll = verifyEntireMarkdown(afterBlock, '2026-11-05');
    expect(afterAll).not.toContain('==[AI');
    expect(afterAll).toContain('Signal velocity reaches 0.5 to 5 mm/s in soil.');
    expect(afterAll).toContain('ai_status: verified');
    expect(afterAll).toContain('verified_at: 2026-11-05');
  });

  it('computes bidirectional backlinks, stub nodes, unlinked mentions, and 1-click term linking', () => {
    const snap = buildVaultSnapshot([
      { relPath: 'Mycelium Network.md', rawMarkdown: sampleNote },
      {
        relPath: 'Fungi.md',
        rawMarkdown: `---\ntitle: Fungi\nai_status: verified\n---\nFungi grow Mycelium threads in soil.`,
      },
    ]);

    const fungiId = 'fungi';
    const mycId = 'mycelium-network';

    expect(snap.backlinks[fungiId]).toHaveLength(1);
    expect(snap.backlinks[fungiId][0].source_id).toBe(mycId);

    expect(snap.unlinked_mentions[mycId]).toHaveLength(1);
    expect(snap.unlinked_mentions[mycId][0].matched_term).toBe('Mycelium');

    const linkedMd = linkTermInMarkdown(
      snap.notes.find((n) => n.id === fungiId)!.raw_markdown,
      'Mycelium',
      'Mycelium Network'
    );
    expect(linkedMd).toContain('[[Mycelium Network|Mycelium]]');
  });

  it('simulates Obsidian force-directed graph physics and local subgraph depth filtering', () => {
    const snap = buildVaultSnapshot([
      { relPath: 'Mycelium Network.md', rawMarkdown: sampleNote },
      {
        relPath: 'Fungi.md',
        rawMarkdown: `---\ntitle: Fungi\n---\nConnected to [[Mycelium Network]]`,
      },
    ]);

    const sim = new ObsidianGraphSimulator(snap.graph_nodes, snap.graph_edges);
    expect(sim.nodes.length).toBeGreaterThanOrEqual(3);
    sim.tick();
    expect(Number.isFinite(sim.nodes[0].x)).toBe(true);

    const sub = filterLocalSubgraph(snap.graph_nodes, snap.graph_edges, 'fungi', 1);
    expect(sub.nodes.some((n) => n.id === 'mycelium-network')).toBe(true);
  });

  it('safely marks prose as AI without corrupting WikiLinks, headings, URLs, YAML frontmatter, or existing AI spans', () => {
    const complexMd = `---
title: Mycelium
tags: [biology]
sources:
  - https://en.wikipedia.org/wiki/Mycelium
ai_status: verified
---

# Mycelium

Connected to [[Mycelium]] and ![[assets/Mycelium.svg]].
In nature, Mycelium forms vast underground networks.
Already flagged: ==[AI:manual] Mycelium== in soil.
`;

    // Selecting "Mycelium" must NOT touch YAML frontmatter, "# Mycelium" heading, "[[Mycelium]]", "![[assets/Mycelium.svg]]", or "==[AI:manual] Mycelium=="
    // It should ONLY wrap the plain prose "Mycelium" in "In nature, Mycelium forms..."
    const flagged = markSelectionAsAiSafely(complexMd, 'Mycelium');
    expect(flagged).toContain('title: Mycelium');
    expect(flagged).toContain('- https://en.wikipedia.org/wiki/Mycelium');
    expect(flagged).toContain('# Mycelium');
    expect(flagged).toContain('[[Mycelium]]');
    expect(flagged).toContain('![[assets/Mycelium.svg]]');
    expect(flagged).not.toContain('[[==[AI');
    expect(flagged).not.toContain('==[AI:manual] ==[AI');
    expect(flagged).toContain('In nature, ==[AI:manual] Mycelium== forms vast underground networks.');
    expect(flagged).toContain('ai_status: partial');

    // Unmarking restores plain prose and transitions ai_status when all AI spans are removed
    const unflagged1 = unmarkAiSpanSafely(flagged, 'Mycelium');
    const unflagged2 = unmarkAiSpanSafely(unflagged1, 'Mycelium');
    expect(unflagged2).not.toContain('==[AI');
    expect(unflagged2).toContain('ai_status: verified');
  });

  it('normalizes bold/italic Hypha links to Obsidian-compatible **[[Target]]** syntax', () => {
    const raw = `We study [[**Mycelium Network**]] and [[*Fungi*]] and [[Hyphae|**Root Thread**]].`;
    const normalized = normalizeObsidianFormattedLinks(raw);
    expect(normalized).toBe(
      `We study **[[Mycelium Network]]** and *[[Fungi]]* and **[[Hyphae|Root Thread]]**.`
    );

    const mdWithBoldTerm = `---\ntitle: Test\n---\nThis is **Fungi** in soil.`;
    const linked = linkTermInMarkdown(mdWithBoldTerm, 'Fungi', 'Fungi');
    expect(linked).toContain('**[[Fungi]]**');
    expect(linked).not.toContain('[[**Fungi**]]');
  });

  it('losslessly preserves custom Obsidian YAML properties and optional # H1 presence on save', () => {
    const obsidianRawWithoutH1 = `---
title: Cordyceps
cssclasses: [wide-page, botanical-card]
created: 2026-01-15
author: Jay Jetsada
publish: true
custom_list:
  - item-alpha
  - item-beta
tags: [fungi, entomopathogenic]
---

Cordyceps is a genus of ascomycete fungi that includes about 600 species.`;

    const existingDoc = parseNote('Biology/Cordyceps.md', obsidianRawWithoutH1);
    const saved = serializeMarkdownLossless({
      originalRaw: obsidianRawWithoutH1,
      title: 'Cordyceps Militaris',
      scope: '',
      aliasesStr: 'Zombie Fungus, ถั่งเช่า',
      tagsStr: 'fungi, medicinal',
      sourcesStr: 'https://en.wikipedia.org/wiki/Cordyceps',
      bodyContent: 'Cordyceps is a genus of ascomycete fungi that includes about 600 species.',
      existingNote: existingDoc,
    });

    // Must preserve custom Obsidian properties and multi-line list
    expect(saved).toContain('cssclasses: [wide-page, botanical-card]');
    expect(saved).toContain('created: 2026-01-15');
    expect(saved).toContain('author: Jay Jetsada');
    expect(saved).toContain('publish: true');
    expect(saved).toContain('custom_list:');
    expect(saved).toContain('  - item-alpha');
    expect(saved).toContain('  - item-beta');
    // Updated structured fields
    expect(saved).toContain('title: Cordyceps Militaris');
    expect(saved).toContain('aliases: [Zombie Fungus, ถั่งเช่า]');
    expect(saved).toContain('tags: [fungi, medicinal]');
    // Because original note had NO "# H1" heading in body, it must NOT force one!
    expect(saved).not.toContain('# Cordyceps Militaris');
  });

  it('strips %%Obsidian comments%% in Read mode and skips comments during AI flagging and Hypha linking', () => {
    const mdWithComments = `---
title: Spore
---
Visible before %%hidden inline comment with Spore and Fungi%% visible after.
%%
Multi-line comment block
mentioning Fungi and Spore
%%
Real prose mentioning Fungi in nature.`;

    const stripped = stripObsidianComments(mdWithComments);
    expect(stripped).not.toContain('hidden inline comment');
    expect(stripped).not.toContain('Multi-line comment block');
    expect(stripped).toContain('Visible before  visible after.');
    expect(stripped).toContain('Real prose mentioning Fungi in nature.');

    // Linking "Fungi" must skip the %%...%% comments and only link the real prose
    const linked = linkTermInMarkdown(mdWithComments, 'Fungi', 'Fungi');
    expect(linked).toContain('%%hidden inline comment with Spore and Fungi%%');
    expect(linked).toContain('Real prose mentioning [[Fungi]] in nature.');

    // Flagging "Fungi" as AI must also skip the %%...%% comments
    const flagged = markSelectionAsAiSafely(mdWithComments, 'Fungi');
    expect(flagged).toContain('%%hidden inline comment with Spore and Fungi%%');
    expect(flagged).toContain('Real prose mentioning ==[AI:manual] Fungi== in nature.');
  });

  it('extracts #Heading sections and #^block-id blocks for Obsidian transclusion and resolves subfolder links', () => {
    const noteBody = `# Symbiosis

Intro paragraph about symbiosis ^intro-blk

## Mycorrhizal Exchange

Carbon flows from tree to fungus.
Phosphorus flows from fungus to tree. ^exchange-blk

### Sub-mechanism

Detailed sub-mechanism text.

## Parasitic Phase

Different section.`;

    const byHeading = extractNoteSectionOrBlock(noteBody, 'Mycorrhizal Exchange');
    expect(byHeading).toContain('Carbon flows from tree to fungus.');
    expect(byHeading).toContain('Detailed sub-mechanism text.');
    expect(byHeading).not.toContain('Different section.');

    const byBlockId = extractNoteSectionOrBlock(noteBody, '^intro-blk');
    expect(byBlockId).toBe('Intro paragraph about symbiosis');

    // Subfolder shortest-path & path-qualified link resolution
    const snap = buildVaultSnapshot([
      {
        relPath: 'Biology/Fungi/Mycorrhiza.md',
        rawMarkdown: `---\ntitle: Mycorrhiza\n---\nLinks to [[#Symbiosis]] and [[Tree Root]].`,
      },
      {
        relPath: 'Forest.md',
        rawMarkdown: `---\ntitle: Forest\n---\nPath link [[Biology/Fungi/Mycorrhiza|Mycorrhizal Network]] and short link [[Mycorrhiza#^intro-blk]].`,
      },
    ]);

    expect(snap.backlinks['mycorrhiza']).toBeDefined();
    expect(snap.backlinks['mycorrhiza'].length).toBeGreaterThanOrEqual(1);
    expect(snap.backlinks['mycorrhiza'][0].source_id).toBe('forest');
  });
});
