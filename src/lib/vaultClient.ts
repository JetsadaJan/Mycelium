  public async importVaultFiles(
    files: Array<{ relPath: string; rawMarkdown: string }>,
    folderName: string
  ): Promise<VaultSnapshot> {
    const id = `imported-${normalizeId(folderName)}-${Date.now().toString().slice(-4)}`;
    const record: ColonyRecord = {
      id,
      name: folderName,
      path: `local-folder://${folderName}`,
      nodeCount: files.length,
      lastOpenedAt: new Date().toISOString().slice(0, 16).replace('T', ' '),
      sourceType: 'imported',
    };
    this.colonies.unshift(record);
    this.activeColonyId = id;
    this.localFiles = files;
    this.localLog = [];
    this.persistColonyRegistry();
    this.persistLocalState();
    return buildVaultSnapshot(this.localFiles, record.path, this.localLog);
  }

