  public async researchWithAi(req: AiResearchRequest): Promise<AiResearchResponse> {
    try {
      const res = await fetch('/api/ai/research', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(req),
      });
      if (res.ok) {
        return await res.json();
      }
    } catch {
      // Fallback browser Wikipedia + LLM synthesis
    }

    const topic = req.topic.trim();
    let extract = `${topic} is an interconnected domain concept within the knowledge graph awaiting primary source review and expansion.`;
    let sourceUrl = `https://en.wikipedia.org/wiki/${encodeURIComponent(topic.replace(/\s+/g, '_'))}`;

    try {
      const wikiRes = await fetch(
        `https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(
          topic.replace(/\s+/g, '_')
        )}`
      );
      if (wikiRes.ok) {
        const data = await wikiRes.json();
        if (data.extract) extract = data.extract;
        if (data.content_urls?.desktop?.page) sourceUrl = data.content_urls.desktop.page;
      }
    } catch {
      // Keep default synthesis
    }

    const relatedLinks = req.existing_titles
      .filter((t) => normalizeId(t) !== normalizeId(topic))
      .slice(0, 3)
      .map((t) => `[[${t}]]`)
      .join(' • ');

    const providerLabel =
      req.mode === 'ollama'
        ? `ollama:${req.model || 'llama3.2'}`
        : req.mode === 'api'
        ? `api:${req.model || 'gemini-2.5-flash'}`
        : 'agent-protocol';

    const callout = `> [!ai] Generated by AI (${providerLabel}) — Pending Human Verification\n> ${extract
      .split('\n')
      .join('\n> ')}`;

    const markdown_page = `---
title: ${topic}
tags: [colony, ai-draft]
ai_status: unverified
ai_source: ${providerLabel}
sources:
  - "${sourceUrl}"
---

# ${topic}

${callout}

## Key Claims Pending Verification

- ==[AI:${providerLabel}] Summary synthesis for ${topic} was compiled automatically and requires human review before verification==
${relatedLinks ? `\nConnected Colony Nodes: ${relatedLinks}\n` : ''}`;

    const agent_prompt = `Research "${topic}" and create or update \`${topic}.md\` in the Colony following \`AGENTS.md\`:
1. Add YAML Frontmatter (\`title: ${topic}\`, \`ai_status: unverified\`, \`ai_source: agent\`, \`sources: ["${sourceUrl}"]\`).
2. Wrap AI-synthesized paragraphs in \`> [!ai] AI Research (Unverified)\`.
3. Wrap specific statistics or factual claims in \`==[AI] ...==\`.
4. Connect related Nodes using \`[[Hyphae]]\` to existing Colony Nodes: ${req.existing_titles
      .slice(0, 8)
      .join(', ')}`;

    return {
      title: topic,
      markdown_page,
      markdown_block: `${callout}\n\n- ==[AI:${providerLabel}] Additional synthesized notes on ${topic} pending verification==`,
      sources: [sourceUrl],
      provider_used: providerLabel,
      agent_prompt,
    };
  }
